<?php

namespace robuust\reverserelations\upgrade;

use Composer\InstalledVersions;
use Craft;
use craft\db\Query;
use craft\db\Table;
use craft\elements\Category;
use craft\elements\Entry;
use craft\fields\Categories;
use craft\fields\Entries;
use craft\models\FieldLayout;
use robuust\reverserelations\fields\ReverseCategories;
use robuust\reverserelations\fields\ReverseEntries;
use RuntimeException;
use Throwable;

/** Preserves Reverse Categories field identity while Craft entrifies its categories. */
final class ReverseCategoriesUpgrade
{
    /**
     * Capture the fields, category IDs and field instances before running entrify.
     *
     * @return array
     */
    public function capture(): array
    {
        $projectConfig = Craft::$app->getProjectConfig();
        $fieldService = Craft::$app->getFields();
        $groups = [];
        foreach (Craft::$app->getCategories()->getAllGroups() as $group) {
            $groups[$group->uid] = $group;
        }

        $fields = [];
        $relatedFields = [];
        $groupUids = [];
        foreach ($projectConfig->get('fields') ?? [] as $uid => $config) {
            if (($config['type'] ?? null) !== ReverseCategories::class) {
                continue;
            }

            $handle = $config['handle'];
            $settings = $config['settings'] ?? [];
            $field = $fieldService->getFieldByUid($uid);
            if (!$field instanceof ReverseCategories) {
                throw new RuntimeException("The existing field “{$handle}” could not be loaded.");
            }

            if (!empty($settings['selectionCondition']['conditionRules'])) {
                throw new RuntimeException("Replace the category selection rules on “{$handle}” before migrating it.");
            }

            $targetUid = $settings['targetFieldId'] ?? null;
            $target = $targetUid ? $fieldService->getFieldByUid($targetUid) : null;
            if (!$target instanceof Categories || $target instanceof ReverseCategories) {
                throw new RuntimeException("“{$handle}” must point to an existing Categories field.");
            }

            $sources = $this->categorySources($settings, array_keys($groups));
            if (!$sources) {
                throw new RuntimeException("“{$handle}” has no category groups to convert.");
            }

            if (($settings['maintainHierarchy'] ?? true) && count($sources) > 1) {
                throw new RuntimeException("“{$handle}” requires a single category group to preserve Maintain hierarchy.");
            }

            $targetGroups = $this->categorySources($target->getSettings(), array_keys($groups));
            $fields[$uid] = [
                'id' => (int) $field->id,
                'config' => $config,
                'sources' => $sources,
                'targetId' => (int) $target->id,
            ];
            $relatedFields[$uid] = true;
            $relatedFields[$targetUid] = true;
            array_push($groupUids, ...$sources, ...$targetGroups);
        }

        foreach ($fieldService->getAllFields(false) as $field) {
            if ($field instanceof ReverseCategories && !isset($fields[$field->uid])) {
                throw new RuntimeException("The field “{$field->handle}” is missing from the global project config.");
            }
        }

        $requiredGroups = array_fill_keys($groupUids, true);
        $groupPlans = [];
        foreach ($groups as $uid => $group) {
            $layoutFields = $this->fieldInstances($group->getFieldLayout(), $relatedFields);
            if (!isset($requiredGroups[$uid]) && !$layoutFields) {
                continue;
            }

            $groupPlans[$uid] = [
                'handle' => $group->handle,
                'elements' => Category::find()->groupId($group->id)->site('*')->unique()->status(null)->ids(),
                'layoutFields' => $layoutFields,
            ];
        }

        return ['version' => 1, 'fields' => $fields, 'groups' => $groupPlans];
    }

    /**
     * Convert the original config in place, after confirming the mapped groups were entrified.
     *
     * @param array                 $plan
     * @param array<string, string> $sectionHandles
     *
     * @return int Number of converted fields
     */
    public function apply(array $plan, array $sectionHandles): int
    {
        if (($plan['version'] ?? null) !== 1 || !is_array($plan['fields'] ?? null) || !is_array($plan['groups'] ?? null)) {
            throw new RuntimeException('Use a plan generated by this tool.');
        }

        $projectConfig = Craft::$app->getProjectConfig();
        $fieldService = Craft::$app->getFields();
        $sections = [];
        foreach ($plan['groups'] as $uid => $group) {
            $handle = $group['handle'];
            $sectionHandle = $sectionHandles[$handle] ?? null;
            $section = $sectionHandle ? Craft::$app->getEntries()->getSectionByHandle($sectionHandle) : null;
            if (!$section) {
                throw new RuntimeException("Map category group “{$handle}” to its new section.");
            }

            $typeIds = [];
            foreach (array_chunk($group['elements'], 500) as $elementIds) {
                $entryTypes = (new Query())
                    ->select('entry.typeId')
                    ->from(['entry' => Table::ENTRIES])
                    ->innerJoin(['element' => Table::ELEMENTS], '[[element.id]] = [[entry.id]]')
                    ->where([
                        'entry.id' => $elementIds,
                        'entry.sectionId' => $section->id,
                        'element.type' => Entry::class,
                    ])
                    ->column();

                if (count($entryTypes) !== count($elementIds)) {
                    throw new RuntimeException("Not all categories from “{$handle}” were converted in “{$sectionHandle}”.");
                }

                array_push($typeIds, ...$entryTypes);
            }

            $matchingTypes = [];
            foreach ($section->getEntryTypes() as $entryType) {
                if (!array_diff($group['layoutFields'], $this->fieldInstances($entryType->getFieldLayout()))) {
                    $matchingTypes[] = $entryType->id;
                }
            }

            if (!$matchingTypes || array_diff($typeIds, $matchingTypes)) {
                throw new RuntimeException("The converted entry types in “{$sectionHandle}” must retain the relation fields from “{$handle}”.");
            }

            $sections[$uid] = $section->uid;
        }

        if (count(array_unique($sections)) !== count($sections)) {
            throw new RuntimeException('Use a separate destination section for each category group.');
        }

        $currentFields = $projectConfig->get('fields') ?? [];
        $unplanned = array_diff_key(array_filter($currentFields, fn (array $field) => $field['type'] === ReverseCategories::class), $plan['fields']);
        if ($unplanned) {
            throw new RuntimeException('This project has Reverse Categories fields that are missing from the migration plan.');
        }

        $changes = [];
        foreach ($plan['fields'] as $uid => $field) {
            $original = $field['config'];
            $handle = $original['handle'];
            $targetUid = $original['settings']['targetFieldId'];
            $target = $fieldService->getFieldByUid($targetUid);
            if (!$target instanceof Entries || $target instanceof ReverseEntries || (int) $target->id !== $field['targetId']) {
                throw new RuntimeException("The original target field for “{$handle}” must already be converted to Entries.");
            }

            $current = $currentFields[$uid] ?? null;
            if ((int) $fieldService->getFieldByUid($uid)?->id !== $field['id']) {
                throw new RuntimeException("The original field “{$handle}” could not be found.");
            }

            $converted = $original;
            $converted['type'] = ReverseEntries::class;
            $converted['settings']['sources'] = array_map(fn (string $groupUid) => 'section:'.$sections[$groupUid], $field['sources']);
            $converted['settings']['maintainHierarchy'] ??= true;
            unset(
                $converted['settings']['source'],
                $converted['settings']['allowMultipleSources'],
                $converted['settings']['allowLimit'],
                $converted['settings']['allowLargeThumbsView'],
                $converted['settings']['selectionCondition'],
            );

            if ($current == $converted) {
                continue;
            }

            if ($current != $original) {
                throw new RuntimeException("The configuration of “{$handle}” changed after the plan was captured.");
            }

            $changes[$uid] = $converted;
        }

        if (!$changes) {
            return 0;
        }

        Craft::$app->getDb()->transaction(function () use ($projectConfig, $changes) {
            foreach ($changes as $uid => $config) {
                $projectConfig->set('fields.'.$uid, $config, 'Convert Reverse Categories field');
            }

            $projectConfig->saveModifiedConfigData();
        });
        $projectConfig->writeYamlFiles();

        return count($changes);
    }

    /**
     * Resolve the legacy single source, scoped source list or wildcard.
     *
     * @param array        $settings
     * @param list<string> $groupUids
     *
     * @return list<string>
     */
    private function categorySources(array $settings, array $groupUids): array
    {
        $sources = (array) (($settings['sources'] ?? null) ?: ($settings['source'] ?? '*'));
        if (in_array('*', $sources, true)) {
            return $groupUids;
        }

        $result = [];
        foreach ($sources as $source) {
            if (!str_starts_with($source, 'group:') || !in_array(substr($source, 6), $groupUids, true)) {
                throw new RuntimeException("Unknown category source “{$source}”. Capture the plan before running entrify.");
            }

            $result[] = substr($source, 6);
        }

        return array_values(array_unique($result));
    }

    /**
     * Identify layout fields by both UID and the handle used on the layout.
     *
     * @param FieldLayout              $layout
     * @param array<string, true>|null $filter
     *
     * @return list<string>
     */
    private function fieldInstances(FieldLayout $layout, ?array $filter = null): array
    {
        $instances = [];
        foreach ($layout->getCustomFields() as $field) {
            if ($filter === null || isset($filter[$field->uid])) {
                $instances[] = "{$field->uid}:{$field->handle}";
            }
        }

        return $instances;
    }
}

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit(1);
}

$usage = <<<'TEXT'
Run from the Craft 5 project root with Reverse Relations 3.x installed.

  php prepare-craft-6.php plan > reverse-categories.json
  php prepare-craft-6.php apply reverse-categories.json categoryGroup=newSection [...]

TEXT;

if (in_array($argv[1] ?? null, ['-h', '--help'], true)) {
    fwrite(STDOUT, $usage);
    exit(0);
}

try {
    $action = $argv[1] ?? null;
    if (($action !== 'plan' || count($argv) !== 2) && ($action !== 'apply' || count($argv) < 3)) {
        throw new RuntimeException($usage);
    }

    if (!is_file('bootstrap.php')) {
        throw new RuntimeException('Run the helper from the Craft 5 project root.');
    }

    require 'bootstrap.php';

    $craftVersion = class_exists(InstalledVersions::class) ? InstalledVersions::getVersion('craftcms/cms') : null;
    if (!str_starts_with($craftVersion ?? '', '5.')) {
        throw new RuntimeException('This helper runs on Craft 5, before replacing it with Craft 6.');
    }

    $app = require CRAFT_VENDOR_PATH.'/craftcms/cms/bootstrap/console.php';
    if (!class_exists(ReverseCategories::class) || !$app->getPlugins()->getPlugin('reverserelations')) {
        throw new RuntimeException('Install and enable Reverse Relations 3.x in this Craft 5 project first.');
    }

    $upgrade = new ReverseCategoriesUpgrade();
    if ($action === 'plan') {
        fwrite(STDOUT, json_encode($upgrade->capture(), JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR).PHP_EOL);
        exit(0);
    }

    if (!is_readable($argv[2])) {
        throw new RuntimeException('The migration plan could not be read.');
    }

    $plan = json_decode(file_get_contents($argv[2]), true, flags: JSON_THROW_ON_ERROR);
    $sections = [];
    foreach (array_slice($argv, 3) as $mapping) {
        [$group, $section] = array_pad(explode('=', $mapping, 2), 2, null);
        if (!$group || !$section || isset($sections[$group])) {
            throw new RuntimeException('Pass one categoryGroup=newSection mapping per group.');
        }

        $sections[$group] = $section;
    }

    $converted = $upgrade->apply($plan, $sections);
    fwrite(STDOUT, "Converted {$converted} Reverse Categories field(s).".PHP_EOL);
} catch (Throwable $exception) {
    fwrite(STDERR, $exception->getMessage().PHP_EOL);
    exit(1);
}
